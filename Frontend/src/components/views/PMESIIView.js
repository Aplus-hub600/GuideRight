import React from 'react';
import { AlertCircle, RefreshCcw, X } from 'lucide-react';
import { PMESII_DATA } from '../../utils/constants';
import LoadingSpinner from '../common/LoadingSpinner';
import ErrorMessage from '../common/ErrorMessage';
import PinButton from '../common/PinButton';

/**
 * PMESII/ASCOPE Matrix view component
 * @param {object} props - Component props
 * @param {boolean} props.loading - Whether data is loading
 * @param {string} props.error - Error message if any
 * @param {function} props.onRetry - Function to retry data fetching
 * @param {Set} props.pinnedItems - Set of pinned item IDs
 * @param {function} props.onTogglePin - Function to toggle pin status
 * @returns {JSX.Element} PMESII view component
 */
const PMESIIView = ({
  loading = false,
  error = null,
  onRetry,
  pinnedItems = new Set(),
  onTogglePin
}) => {
  const categories = ['Areas', 'Structures', 'Capabilities', 'Organizations', 'People', 'Events'];
  const columns = ['Political', 'Military', 'Economic', 'Social', 'Information', 'Infrastructure'];

  return (
    <div className="bg-white/70 backdrop-blur-md rounded-3xl shadow-sm overflow-hidden h-full flex flex-col">
      {/* Header */}
      <div className="p-6 border-b border-gray-100 flex-shrink-0">
        <div className="flex items-center justify-between">
          <h2 className="text-2xl font-medium text-gray-800">PMESII/ASCOPE Analysis</h2>
          <div className="text-sm text-gray-600">
            The content in each cell is generated by AI based on the latest data and trends.
          </div>
        </div>
      </div>
      
      {/* AI Summary */}
      <div className="p-6 bg-blue-50/70 backdrop-blur-md border-b border-gray-100 flex-shrink-0">
        <div className="flex items-start gap-4">
          <AlertCircle className="w-6 h-6 text-blue-600 flex-shrink-0 mt-1" />
          <div className="flex-1">
            <h3 className="text-lg font-medium text-gray-800 mb-2">AI Summary</h3>
            <p className="text-gray-700">
              BLUF summary of PMESII analysis shows stable political environment, 
              growing economic indicators, and positive social development trends.
            </p>
          </div>
          <div className="flex gap-2">
            <PinButton
              itemId="pmesii-summary"
              isPinned={pinnedItems.has('pmesii-summary')}
              onTogglePin={onTogglePin}
              size="sm"
            />
            <button 
              onClick={() => onRegenerateAISummary && onRegenerateAISummary() }
              className="w-8 h-8 rounded-lg hover:bg-gray-200 flex items-center justify-center"
              title="Regenerate summary for current filters"
            >
              <RefreshCcw className="w-4 h-4 text-gray-600" />
            </button>
          </div>
        </div>
      </div>
      
      {/* Content */}
      <div className="flex-1 p-6 overflow-y-auto scrollbar-thin scrollbar-thumb-gray-300 scrollbar-track-gray-100">
        {loading ? (
          <LoadingSpinner section="PMESII matrix" />
        ) : error ? (
          <ErrorMessage 
            error={error} 
            onRetry={onRetry}
            title="Failed to load PMESII data"
          />
        ) : (
          <div className="bg-white border border-gray-200 rounded-lg overflow-hidden">
            <div className="overflow-x-auto">
              <table className="w-full min-w-max">
                {/* Table Header */}
                <thead>
                  <tr className="bg-gray-100">
                    <th className="border border-gray-300 p-3 text-left font-medium text-gray-800 w-32 sticky left-0 bg-gray-100">
                      Category
                    </th>
                    {columns.map((column, index) => (
                      <th key={index} className="border border-gray-300 p-3 text-center font-medium text-gray-800 w-48">
                        <div className="flex flex-col">
                          <span className="text-xl font-bold text-blue-600">
                            {column.charAt(0)}
                          </span>
                          <span className="text-sm">{column}</span>
                        </div>
                      </th>
                    ))}
                  </tr>
                </thead>
                
                {/* Table Body */}
                <tbody>
                  {PMESII_DATA.map((row, rowIndex) => (
                    <tr key={rowIndex} className="hover:bg-gray-50">
                      {/* Category Header */}
                      <td className="border border-gray-300 p-3 bg-gray-50 font-medium text-gray-800 text-center align-top w-32 sticky left-0">
                        <div className="font-semibold">
                          {row.category}
                        </div>
                      </td>
                      
                      {/* Matrix Cells */}
                      {row.data.map((cell, cellIndex) => {
                        const cellId = `pmesii-${rowIndex}-${cellIndex}`;
                        const isPinned = pinnedItems.has(cellId);
                        
                        return (
                          <td 
                            key={cellIndex} 
                            className={`border border-gray-300 p-0 group relative transition-colors w-48 ${
                              isPinned ? 'bg-blue-50 hover:bg-blue-100' : 'hover:bg-gray-50'
                            }`}
                          >
                            <div className="h-full flex flex-col min-h-[140px]">
                              {/* Cell Content */}
                              <div className="flex-1 p-3 overflow-y-auto scrollbar-thin scrollbar-thumb-gray-400 scrollbar-track-transparent">
                                <p className="text-sm text-gray-700 leading-relaxed">
                                  {cell}
                                </p>
                              </div>
                              
                              {/* Pin Button */}
                              <div className="absolute bottom-2 right-2 z-10">
                                <button
                                  onClick={() => onTogglePin(cellId)}
                                  className={`px-2 py-1 text-xs rounded font-medium transition-all ${
                                    isPinned
                                      ? 'bg-blue-600 text-white opacity-100'
                                      : 'bg-gray-800 text-white hover:bg-gray-700 opacity-0 group-hover:opacity-100'
                                  }`}
                                  title={isPinned ? `Unpin ${categories[rowIndex]} - ${columns[cellIndex]}` : `Pin ${categories[rowIndex]} - ${columns[cellIndex]}`}
                                >
                                  {isPinned ? 'Pinned' : 'Pin'}
                                </button>
                              </div>
                              
                              {/* Cell Coordinates (helpful for debugging) */}
                              <div className="absolute top-1 left-1 text-xs text-gray-400 opacity-0 group-hover:opacity-50">
                                {rowIndex},{cellIndex}
                              </div>
                            </div>
                          </td>
                        );
                      })}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            
            {/* Matrix Legend */}
            <div className="p-4 bg-transparent">
              <div className="grid grid-cols-3 gap-4 text-xs text-gray-600">
                <div>
                  <h4 className="font-medium text-gray-800 mb-2">PMESII Framework:</h4>
                  <ul className="space-y-1">
                    <li><span className="font-medium">P</span> - Political factors</li>
                    <li><span className="font-medium">M</span> - Military factors</li>
                    <li><span className="font-medium">E</span> - Economic factors</li>
                    <li><span className="font-medium">S</span> - Social factors</li>
                    <li><span className="font-medium">I</span> - Information factors</li>
                    <li><span className="font-medium">I</span> - Infrastructure factors</li>
                  </ul>
                </div>
                <div>
                  <h4 className="font-medium text-gray-800 mb-2">ASCOPE Elements:</h4>
                  <ul className="space-y-1">
                    <li><span className="font-medium">A</span> - Areas factors</li>
                    <li><span className="font-medium">S</span> - Structures factors</li>
                    <li><span className="font-medium">C</span> - Capabilities factors</li>
                    <li><span className="font-medium">O</span> - Organizations factors</li>
                    <li><span className="font-medium">P</span> - People factors</li>
                    <li><span className="font-medium">E</span> - Events factors</li>
                  </ul>
                </div>
                <div>
                  <h4 className="font-medium text-gray-800 mb-2">Usage:</h4>
                  <ul className="space-y-1">
                    <li>• Hover over cells to pin them</li>
                    <li>• Pinned cells appear in reports</li>
                    <li>• Each cell contains specific guidance generated by the AI agent</li>
                  </ul>
                </div>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};

export default PMESIIView;